//! Portable radix-two negacyclic NTT over primes below $2^{62}$.
//!
//! Ported from jali (`src/math/ntt.rs`, MIT, by the same author), with the size limit raised from
//! 1024 to [`MAX_DEGREE`] $= 4096$ and a new prime table [`NTT_PRIMES`].
//!
//! A plan precomputes every twiddle of every stage, the twists and the bit-reversal permutation,
//! each multiplier with its Shoup constant $\lfloor w 2^{64}/p \rfloor$, so that a transform
//! needs no division: products by constants are Shoup products and sums reduce by one
//! conditional subtraction. For a primitive $2d$-th root of unity $\psi$ modulo $p$,
//! [`NttPlan::forward`] maps the coefficients of $a \in \mathbb Z_p\[X\]/(X^d + 1)$ to the
//! evaluations $a(\psi^{2j+1})$, $j < d$, in natural order, so a negacyclic product is a
//! pointwise product between a forward and an inverse transform. The RNS products of
//! [`crate::rns`] use the Montgomery form instead: values times $R = 2^{64}$, put in by the twist
//! of the forward transform, kept by the Montgomery products of pointwise multiplication and by
//! sums, and taken out by the untwist of the inverse transform.
//!
//! The NTT is an implementation device; the paper only needs exact products in $\mathcal R_q$
//! (draft `4_preliminaries.tex`:67).

use crate::{
    arith::{add_mod, is_prime, mul_mod, pow_mod, reduce, shoup, shoup_mul, sub_mod},
    error::{Error, Result},
};

/// The largest transform size: negacyclic transforms of every power-of-two size
/// $2 \le d \le 4096$ are supported, which covers ring degrees up to 2048 and the ring of degree
/// $2d$ used for quotients by $X^d + 1$ (`docs/m0-spec.md`, `ntt`).
pub const MAX_DEGREE: usize = 4096;

/// NTT primes $p < 2^{62}$ with $2^{13} \mid p - 1$, in descending order, each with a primitive
/// $2^{13}$-th root of unity: the moduli of the exact products in $\mathcal R_q$ (draft
/// `4_preliminaries.tex`:67), replacing jali's table of order-2048 roots (`src/params/moduli.rs`).
///
/// Generated by `crates/math/tools/ntt_primes.sage` (SageMath 10.9): the nine largest primes
/// below $2^{62}$ with $p \equiv 1 \pmod{2^{13}}$, and for each the root $g^{(p-1)/2^{13}}$ for the
/// smallest primitive root $g$ modulo $p$. The root of a transform of size $d$ is
/// $\mathrm{root}^{4096/d}$, a primitive $2d$-th root of unity ([`root_of_unity`]). The product of
/// the nine primes exceeds $2^{557}$; a ring modulus below $2^{63}$ and degree at most 4096 needs
/// at most three of them ([`crate::rns::Plan::new`]).
pub const NTT_PRIMES: [(u64, u64); 9] = [
    (4611686018427322369, 3391169269051246823),
    (4611686018427289601, 814482755461094628),
    (4611686018427215873, 218787204735203926),
    (4611686018427199489, 1593883455304529857),
    (4611686018426953729, 785784704542803931),
    (4611686018426658817, 2329424766364971096),
    (4611686018426454017, 1221839841272230096),
    (4611686018426265601, 809009532893953240),
    (4611686018426257409, 3884705425455714630),
];

/// The primitive $2d$-th root of unity $\mathrm{root}^{4096/d}$ modulo `p`, from a root of order
/// $2 \cdot$ [`MAX_DEGREE`] $= 2^{13}$ as in [`NTT_PRIMES`], for a power of two
/// $d \le$ [`MAX_DEGREE`] (jali, `src/math/ring.rs`, with $1024$ in place of $4096$).
pub fn root_of_unity(p: u64, root: u64, d: usize) -> u64 {
    debug_assert!(d.is_power_of_two() && d <= MAX_DEGREE);
    pow_mod(root, (MAX_DEGREE / d) as u64, p)
}

/// A validated negacyclic transform plan for one prime $p < 2^{62}$ and one size $d$ (jali,
/// `src/math/ntt.rs`, `NttPlan`).
#[derive(Clone, Debug)]
pub struct NttPlan {
    p: u64,
    d: usize,
    /// $-p^{-1} \bmod 2^{64}$, for Montgomery reduction.
    neg_inv: u64,
    /// The twiddles of the cyclic transforms with their Shoup constants, stage after stage: the
    /// stage of length `len` holds $\omega^{jd/\mathrm{len}}$ for $j < \mathrm{len}/2$, with
    /// $\omega = \psi^2$ forward and $\omega^{-1}$ inverse.
    forward_twiddles: Vec<(u64, u64)>,
    inverse_twiddles: Vec<(u64, u64)>,
    /// $\psi^i$ and $\psi^{-i} d^{-1}$: the twist and untwist of the public transforms.
    twist: Vec<(u64, u64)>,
    untwist: Vec<(u64, u64)>,
    /// $\psi^i R$ and $\psi^{-i} d^{-1} R^{-1}$ with $R = 2^{64}$: the Montgomery-form twists.
    twist_mont: Vec<(u64, u64)>,
    untwist_mont: Vec<(u64, u64)>,
    /// The bit-reversal permutation of $[0, d)$.
    bit_reverse: Vec<u32>,
}

impl NttPlan {
    /// A plan from a prime $p < 2^{62}$, a power of two $2 \le d \le$ [`MAX_DEGREE`] with
    /// $2d \mid p - 1$, and a primitive $2d$-th root of unity $\psi$ (checked as
    /// $\psi^d \equiv -1$, which for a power of two $d$ means order exactly $2d$); jali,
    /// `NttPlan::new`, with the size limit raised from 1024.
    ///
    /// # Errors
    /// [`Error::Parameter`] if any of these conditions fails.
    pub fn new(p: u64, d: usize, psi: u64) -> Result<Self> {
        if !(2..=MAX_DEGREE).contains(&d)
            || !d.is_power_of_two()
            || p >= (1 << 62)
            || !is_prime(p)
            || !(p - 1).is_multiple_of(2 * d as u64)
            || psi >= p
            || pow_mod(psi, d as u64, p) != p - 1
        {
            return Err(Error::Parameter("NTT prime, degree or root"));
        }
        let root = mul_mod(psi, psi, p);
        let inv_psi = pow_mod(psi, p - 2, p);
        let inv_d = pow_mod(d as u64, p - 2, p);
        // R = 2^64 mod p and its inverse.
        let r = ((1u128 << 64) % u128::from(p)) as u64;
        let r_inv = pow_mod(r, p - 2, p);
        // p^-1 mod 2^64 by Newton's iteration x <- x (2 - p x), which doubles the number of
        // correct low bits; x = 1 is correct modulo 2 since p is odd.
        let mut inv = 1u64;
        for _ in 0..6 {
            inv = inv.wrapping_mul(2u64.wrapping_sub(p.wrapping_mul(inv)));
        }
        debug_assert_eq!(p.wrapping_mul(inv), 1);
        let pair = |w: u64| (w, shoup(w, p));
        let stages = |root: u64| {
            let mut out = Vec::with_capacity(d);
            let mut len = 2;
            while len <= d {
                let step = pow_mod(root, (d / len) as u64, p);
                let mut w = 1;
                for _ in 0..len / 2 {
                    out.push(pair(w));
                    w = mul_mod(w, step, p);
                }
                len *= 2;
            }
            out
        };
        let mut twist = Vec::with_capacity(d);
        let mut untwist = Vec::with_capacity(d);
        let mut twist_mont = Vec::with_capacity(d);
        let mut untwist_mont = Vec::with_capacity(d);
        let (mut t, mut u) = (1u64, inv_d);
        for _ in 0..d {
            twist.push(pair(t));
            untwist.push(pair(u));
            twist_mont.push(pair(mul_mod(t, r, p)));
            untwist_mont.push(pair(mul_mod(u, r_inv, p)));
            t = mul_mod(t, psi, p);
            u = mul_mod(u, inv_psi, p);
        }
        let bits = d.trailing_zeros();
        Ok(Self {
            p,
            d,
            neg_inv: inv.wrapping_neg(),
            forward_twiddles: stages(root),
            inverse_twiddles: stages(pow_mod(root, p - 2, p)),
            twist,
            untwist,
            twist_mont,
            untwist_mont,
            bit_reverse: (0..d as u32)
                .map(|i| i.reverse_bits() >> (32 - bits))
                .collect(),
        })
    }

    /// The plan for prime `index` of [`NTT_PRIMES`] and size $d$, with the root
    /// [`root_of_unity`] (as jali's rings build their plans, `src/math/ring.rs`).
    ///
    /// # Errors
    /// [`Error::Parameter`] for an index outside the table or an unsupported size.
    pub fn from_table(index: usize, d: usize) -> Result<Self> {
        let (p, root) = *NTT_PRIMES
            .get(index)
            .ok_or(Error::Parameter("NTT prime index"))?;
        if !(2..=MAX_DEGREE).contains(&d) || !d.is_power_of_two() {
            return Err(Error::Parameter("NTT prime, degree or root"));
        }
        Self::new(p, d, root_of_unity(p, root, d))
    }

    /// The transform modulus $p$ (jali, `NttPlan::modulus`).
    pub fn modulus(&self) -> u64 {
        self.p
    }

    /// The transform size $d$ (jali, `NttPlan::degree`).
    pub fn degree(&self) -> usize {
        self.d
    }

    fn prepare(&self, values: &mut [u64]) -> Result<()> {
        if values.len() != self.d {
            return Err(Error::Length {
                expected: self.d,
                actual: values.len(),
            });
        }
        for x in values.iter_mut() {
            *x = reduce(*x, self.p);
        }
        Ok(())
    }

    /// The cyclic transform with the stage twiddles `table`, on residues in $[0, p)$.
    fn cyclic(&self, a: &mut [u64], table: &[(u64, u64)]) {
        let p = self.p;
        for (i, j) in self.bit_reverse.iter().enumerate() {
            let j = *j as usize;
            if i < j {
                a.swap(i, j);
            }
        }
        let mut len = 2;
        let mut offset = 0;
        while len <= self.d {
            let half = len / 2;
            let twiddles = &table[offset..offset + half];
            for block in a.chunks_exact_mut(len) {
                let (low, high) = block.split_at_mut(half);
                for ((u, v), (w, w_shoup)) in low.iter_mut().zip(high.iter_mut()).zip(twiddles) {
                    let x = *u;
                    let y = shoup_mul(*v, *w, *w_shoup, p);
                    *u = add_mod(x, y, p);
                    *v = sub_mod(x, y, p);
                }
            }
            offset += half;
            len *= 2;
        }
    }

    /// Multiply each residue by its factor.
    fn scale(&self, a: &mut [u64], factors: &[(u64, u64)]) {
        for (x, (w, w_shoup)) in a.iter_mut().zip(factors) {
            *x = shoup_mul(*x, *w, *w_shoup, self.p);
        }
    }

    /// Transform coefficients $a_0, \dots, a_{d-1}$ (read modulo $p$) to the evaluations
    /// $a(\psi^{2j+1})$, $j = 0, \dots, d-1$ (jali, `NttPlan::forward`; unreduced inputs are
    /// reduced here instead of rejected).
    ///
    /// # Errors
    /// [`Error::Length`] unless `a` has $d$ entries.
    pub fn forward(&self, a: &mut [u64]) -> Result<()> {
        self.prepare(a)?;
        self.scale(a, &self.twist);
        self.cyclic(a, &self.forward_twiddles);
        Ok(())
    }

    /// Invert [`NttPlan::forward`], including the normalization by $d^{-1}$ and the untwist (jali,
    /// `NttPlan::inverse`).
    ///
    /// # Errors
    /// [`Error::Length`] unless `a` has $d$ entries.
    pub fn inverse(&self, a: &mut [u64]) -> Result<()> {
        self.prepare(a)?;
        self.cyclic(a, &self.inverse_twiddles);
        self.scale(a, &self.untwist);
        Ok(())
    }

    /// [`NttPlan::forward`] times $R = 2^{64}$ (the Montgomery form), for $d$ residues in
    /// $[0, p)$.
    pub(crate) fn forward_mont(&self, a: &mut [u64]) {
        debug_assert!(a.len() == self.d && a.iter().all(|x| *x < self.p));
        self.scale(a, &self.twist_mont);
        self.cyclic(a, &self.forward_twiddles);
    }

    /// [`NttPlan::inverse`] of values in Montgomery form, which removes the factor $R$, for $d$
    /// residues in $[0, p)$.
    pub(crate) fn inverse_mont(&self, a: &mut [u64]) {
        debug_assert!(a.len() == self.d && a.iter().all(|x| *x < self.p));
        self.cyclic(a, &self.inverse_twiddles);
        self.scale(a, &self.untwist_mont);
    }

    /// The Montgomery product $a b R^{-1} \bmod p$ of $a, b < p$, in $[0, p)$.
    ///
    /// With $t = ab < p^2$ and $m = t(-p^{-1}) \bmod R$, $t + mp$ is divisible by $R$ and below
    /// $p^2 + Rp < 2^{127}$, and $u = (t + mp)/R < 2p$, so one conditional subtraction reduces
    /// it.
    #[inline(always)]
    pub(crate) fn mont_mul(&self, a: u64, b: u64) -> u64 {
        let t = u128::from(a) * u128::from(b);
        let m = (t as u64).wrapping_mul(self.neg_inv);
        let u = ((t + u128::from(m) * u128::from(self.p)) >> 64) as u64;
        if u >= self.p { u - self.p } else { u }
    }
}

